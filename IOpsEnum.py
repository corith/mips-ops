from enum import IntEnum


class Iops(IntEnum):
    beq = 0x04
    bne = 0x05
    blez = 0x06
    bgtz = 0x07
    addi = 0x08
    addiu = 0x09
    slti = 0x0A
    sltiu = 0x0B
    andi = 0x0C
    ori = 0x0D
    xori = 0x0E
    lui = 0x0F
    lb = 0x20
    lh = 0x21
    lw = 0x23
    lbu = 0x24
    lhu = 0x25
    sb = 0x28
    sh = 0x29
    sw = 0x2B
